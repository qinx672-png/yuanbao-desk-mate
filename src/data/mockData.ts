/* ------------------------------------------------------------------
 * 快问快答里「同桌猜你选哪个」那句话 —— 前端和音频脚本**共用同一份拼装逻辑**
 *
 * ── 为什么这两个函数住在数据层而不是组件里 ──────────────────
 * 这句话是按 quickQuestions 的数据现拼的（题目下标、上一题选了啥都会影响措辞），
 * 所以它不是一句固定的台词，而是**一小撮固定台词**。而预渲染音频要求
 * 「有哪些台词」必须能被穷举出来。
 *
 * 2026-09-13 实测连踩两次：兴趣标签那句（4 个 tag 只有 1 个有音频）、
 * 这里的猜句（5 个变体只有 3 个有音频）—— 表现形式都一样：
 * 走到那个分支时声音**突然从同桌变成浏览器机器音**，演示时最扎眼。
 *
 * 根因是「拼装逻辑只活在组件里，脚本只能靠猜」。放到这儿之后，
 * scripts/gen-voice.mjs 直接 import 同一份函数把变体列全，不会再漏。
 * （和 fallbackLoopFor 同一个套路。）
 * ------------------------------------------------------------------ */

/** 同桌猜你会选哪个下标：'echo' = 跟上一题同一个下标（同维度相邻两题用它，表示真的在往下推） */
export function quickGuessPick(i: number, lastPick: 0 | 1 | undefined): 0 | 1 {
  const g = quickQuestions[i]?.guess
  if (!g) return 0
  return g.pick === 'echo' ? ((lastPick ?? 0) as 0 | 1) : g.pick
}

/**
 * 猜之前先说的那句话。没有 guess 的题返回 null（那题不猜）。
 * @param lastPick 学生上一题选的下标；'echo' 题缺省按 0 处理
 */
export function quickGuessLine(i: number, lastPick: 0 | 1 | undefined): string | null {
  const q = quickQuestions[i]
  const g = q?.guess
  if (!q || !g) return null
  const pick = quickGuessPick(i, lastPick)

  if (g.blind) {
    // 第一题没有任何线索，明说是硬猜 —— 学生才不会往猜的那边靠
    return `第 ${i + 1} 题。我手上还是一点线索都没有，硬猜一个 —— 我猜你选「${q.choices[pick]}」。你选你的，别管我。`
  }
  const last = quickQuestions[i - 1]
  const lastText = last && lastPick !== undefined ? `「${last.choices[lastPick]}」` : '你上一题那个选法'
  return `你上一题选的是${lastText} —— 同一类事，我往下猜：这题你还是「${q.choices[pick]}」。`
}

