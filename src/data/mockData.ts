/* ==================================================================
 * V2 · 容错四步闭环：发现 → 承认 → 修复 → 沉淀（架构说明 五）
 * 准确率做不到 100%，容错闭环必须 100%。
 *
 * ── 这里修掉了一个「看着很像样，其实是假的」的问题 ──────────────
 * 旧版的「承认」写的是：「…我刚才说成了 L₁」。
 * 但整份脚本从头到尾，AI 从没说过 L₁，也从没把电压表那句讲反 ——
 * 它在为一件自己没做过的事道歉。台词是真的，事实是假的。
 * 一个演示「容错」的功能，自己的事实是错的，这是最要命的一种 bug。
 *
 * 现在改成**引用它真说过的那句**：埋了错的小步（node.error）
 * 走完整四步，quote 就是那处原话。
 * ================================================================== */

/**
 * 生成容错四步闭环。
 * @param quote 学生指出的那处错 —— 必须是 AI 在这一步真说过的话
 * @param fix   正确的讲法
 */
export function fallbackLoopFor(quote: string, fix: string): FallbackLoopStep[] {
  return [
    { step: '发现', who: '学生', text: '等一下，我觉得你这句讲反了。' },
    { step: '承认', who: 'AI', text: `我核对了一下教材 —— 你说得对。我刚才那句「${quote}」讲反了。` },
    { step: '修复', who: 'AI', text: fix },
    { step: '沉淀', who: 'AI', text: '这个错我记成「易错点案例」了，下次同类题我会先自查这一步。' },
  ]
}

